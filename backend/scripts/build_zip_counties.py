"""Build backend/data/fl_zip_counties.json from the Census ZIP-to-county relationship file.

Usage: python scripts/build_zip_counties.py <relationship file path or URL> <output json>
"""
import csv
import io
import json
import sys
from pathlib import Path

import requests

FLORIDA = "12"
SOURCE = "https://www2.census.gov/geo/docs/maps-data/data/rel2020/zcta520/tab20_zcta520_county20_natl.txt"


def _text(source):
    if not source.startswith(("http://", "https://")):
        return Path(source).read_text(encoding="utf-8-sig")
    response = requests.get(source, timeout=120, headers={"User-Agent": "EcoLoco-FL (https://github.com/AydinHeugh/EcoLoco-FL)"})
    response.raise_for_status()
    return response.content.decode("utf-8-sig")


def zip_counties(text):
    best = {}
    for row in csv.DictReader(io.StringIO(text), delimiter="|"):
        zip_code, county = row["GEOID_ZCTA5_20"], row["GEOID_COUNTY_20"]
        if not zip_code:
            continue
        land = int(row["AREALAND_PART"] or 0)
        if zip_code not in best or land > best[zip_code][0]:
            best[zip_code] = (land, county, row["NAMELSAD_COUNTY_20"])
    return {
        zip_code: name.removesuffix(" County")
        for zip_code, (_, county, name) in sorted(best.items())
        if county.startswith(FLORIDA)
    }


def main(source, out_path):
    zips = zip_counties(_text(source))
    result = {
        "_comment": (
            "Generated by backend/scripts/build_zip_counties.py from the 2020 Census ZIP-to-county relationship file. "
            "A ZIP that crosses county lines is given the county holding most of its land."
        ),
        "source": SOURCE,
        "zips": zips,
    }
    Path(out_path).write_text(json.dumps(result, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"{len(zips)} Florida ZIP codes in {len(set(zips.values()))} counties")


if __name__ == "__main__":
    main(*sys.argv[1:3])
